let lang = stored() === 'en' ? 'en' : 'zh';
const listeners = new Set();

function stored() {
  try { return globalThis.localStorage?.getItem('centerstage:lang'); } catch { return null; }
}

export function language() { return lang; }

export function t(key, vars) {
  let text = dictionaries[lang][key] ?? dictionaries.zh[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function trServer(text) {
  const value = text == null ? '' : String(text);
  if (lang === 'zh' || !value) return value;
  for (const [pattern, key] of serverPatterns) {
    const match = value.match(pattern);
    if (!match) continue;
    return typeof key === 'function' ? key(match) : t(key);
  }
  return value;
}

export function onLanguage(listener) { listeners.add(listener); }

export function applyDom() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  document.title = t('docTitle');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('.lang-switch [data-lang]').forEach(button => {
    const selected = button.dataset.lang === lang;
    button.classList.toggle('selected', selected);
    button.setAttribute('aria-pressed', selected ? 'true' : 'false');
  });
}

